export type StringKey = keyof typeof strings;

/** A string with the app name and legal entity filled in, and any further `{name}` values. */
export function say(key: StringKey, values: Record<string, string> = {}): string {
  const all: Record<string, string> = { app: config.appName, entity: config.legalEntity, ...values };
  return strings[key].replace(/\{(\w+)\}/g, (whole, name: string) => all[name] ?? whole);
}
