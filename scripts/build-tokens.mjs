#!/usr/bin/env node
// §16.1 step 3: design-system/tokens.css from tokens.json and tokens.extra.json. Same input, same bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../design-system');
const tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));
const extra = JSON.parse(readFileSync(join(dir, 'tokens.extra.json'), 'utf8'));

const lines = [];
const section = (title) => lines.push('', `  /* ${title} */`);
const put = (name, value) => lines.push(`  --${name}: ${value};`);
const kebab = (s) => s.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-');

section('Colour');
for (const t of tokens.color.tokens) put(`color-${t.name}`, t.value);

section('Font stacks');
for (const [name, stack] of Object.entries(tokens.type.families)) put(`font-${name}`, stack);

section('Font faces (family names of the @font-face rules)');
for (const family of new Set(tokens.type.fonts.map((f) => f.family))) put(`font-face-${kebab(family)}`, `"${family}"`);

section('Type styles');
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    put(`text-${s.name}-family`, `var(--font-${group.family})`);
    put(`text-${s.name}-size`, s.fontSize);
    put(`text-${s.name}-line-height`, s.lineHeight);
    put(`text-${s.name}-weight`, s.fontWeight);
    if (s.letterSpacing) put(`text-${s.name}-tracking`, s.letterSpacing);
  }
}

section('Spacing');
for (const t of tokens.spacing.tokens) put(t.name, t.value);

section('Radius');
for (const t of tokens.radius.tokens) put(t.name, t.value);

section('Motion');
const motionNames = Object.keys(extra.motion).filter((k) => k !== 'reduced'); // `reduced` is the prose of the rule below
for (const name of motionNames) put(name, extra.motion[name]);

section('Layers');
for (const [name, value] of Object.entries(extra.layer)) put(`layer-${name}`, value);

section('Breakpoints');
for (const [name, value] of Object.entries(extra.breakpoint)) put(`breakpoint-${name}`, value);

section('Scene');
for (const [name, value] of Object.entries(extra.scene)) put(`scene-${name}`, value);

const instant = motionNames.filter((k) => k !== 'ease-out').map((k) => `    --${k}: 0ms;`);
const css = [
  '/* Generated by scripts/build-tokens.mjs from tokens.json and tokens.extra.json. Never edit by hand. */',
  ':root {',
  ...lines.slice(1),
  '}',
  '',
  `/* ${extra.motion.reduced} */`,
  '@media (prefers-reduced-motion: reduce) {',
  '  :root {',
  ...instant,
  '  }',
  '  *, *::before, *::after {',
  '    animation: none !important;',
  '    transition: none !important;',
  '  }',
  '}',
  '',
].join('\n');

writeFileSync(join(dir, 'tokens.css'), css);
console.log(`tokens.css: ${lines.filter((l) => l.startsWith('  --')).length} custom properties`);
